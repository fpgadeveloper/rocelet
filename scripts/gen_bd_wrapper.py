import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

IFACE = {
    's_axil_': ('S_AXIL', 'aximm'), 'm_axi_': ('M_AXI', 'aximm'),
    's_axis_rx_': ('S_AXIS_RX', 'axis'), 'm_axis_tx_': ('M_AXIS_TX', 'axis'),
    'm_axis_other_': ('M_AXIS_OTHER', 'axis'), 's_axis_other_': ('S_AXIS_OTHER', 'axis'),
    's_axis_wr_data_': ('S_AXIS_WR_DATA', 'axis'), 's_axis_wr_': ('S_AXIS_WR', 'axis'),
    'm_axis_wc_': ('M_AXIS_WC', 'axis'), 'm_axis_send_': ('M_AXIS_SEND', 'axis'),
    'm_axis_rc_': ('M_AXIS_RC', 'axis'),
}


def generate():
    s = open(os.path.join(ROOT, 'rtl', 'rocelet_top.sv')).read()
    phead = s[s.index('#('):s.index(') (')]
    params = re.findall(r"parameter\s+(?:int|bit|logic \[23:0\])?\s*(\w+)\s*=\s*([^,\n]+?),?\s*\n", phead)
    ports = re.findall(r"^\s*(input|output)\s+wire\s+logic\s*(\[[^\]]+\])?\s*(\w+),?",
                       s[s.index(') ('):s.index(');')], re.M)
    busifs = [v[0] for v in IFACE.values()]
    L = ['// SPDX-License-Identifier: MIT', '//',
         '// rocelet_bd - Verilog wrapper of rocelet_top for a Vivado IP integrator module reference (a',
         '// module reference needs a Verilog top). Same ports and parameters as rocelet_top; the',
         '// X_INTERFACE attributes group them into AXI4-Lite (S_AXIL), AXI4 (M_AXI) and AXI-Stream',
         '// interfaces, all in the clock `clk`. GENERATED by scripts/gen_bd_wrapper.py from',
         '// rocelet_top.sv, do not edit; see docs/integration.md.',
         '//', '// Copyright (c) 2026 Opsero Electronic Design Inc.', '', '`timescale 1ns / 1ps', '',
         'module rocelet_bd #(']
    pl = []
    for n, v in params:
        v = v.strip()
        if v.startswith('"'):
            pl.append('    parameter %s = %s' % (n, v))
        elif n == 'QPN_BASE':
            pl.append('    parameter [23:0] %s = %s' % (n, v))
        else:
            pl.append('    parameter integer %s = %s' % (n, v.replace("1'b1", "1").replace("1'b0", "0")))
    L.append(',\n'.join(pl))
    L.append(') (')
    pls = []
    for d, w, n in ports:
        attrs = ''
        if n == 'clk':
            attrs = ('(* X_INTERFACE_INFO = "xilinx.com:signal:clock:1.0 clk CLK" *)\n'
                     '    (* X_INTERFACE_PARAMETER = "ASSOCIATED_BUSIF %s, ASSOCIATED_RESET rst" *)\n    '
                     % ':'.join(busifs))
        elif n == 'rst':
            attrs = ('(* X_INTERFACE_INFO = "xilinx.com:signal:reset:1.0 rst RST" *)\n'
                     '    (* X_INTERFACE_PARAMETER = "POLARITY ACTIVE_HIGH" *)\n    ')
        elif n == 'irq':
            attrs = ('(* X_INTERFACE_INFO = "xilinx.com:signal:interrupt:1.0 irq INTERRUPT" *)\n'
                     '    (* X_INTERFACE_PARAMETER = "SENSITIVITY LEVEL_HIGH" *)\n    ')
        else:
            for pre, (bus, kind) in sorted(IFACE.items(), key=lambda x: -len(x[0])):
                if not n.startswith(pre):
                    continue
                sig = n[len(pre):].upper()
                if kind == 'axis' and sig in ('TDATA', 'TKEEP', 'TVALID', 'TREADY', 'TLAST', 'TUSER'):
                    attrs = '(* X_INTERFACE_INFO = "xilinx.com:interface:axis:1.0 %s %s" *) ' % (bus, sig)
                elif kind == 'aximm':
                    attrs = '(* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 %s %s" *) ' % (bus, sig)
                    if bus == 'S_AXIL' and sig == 'AWADDR':
                        attrs = ('(* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 S_AXIL AWADDR" *)\n'
                                 '    (* X_INTERFACE_PARAMETER = "PROTOCOL AXI4LITE, DATA_WIDTH 32, ADDR_WIDTH 16" *)\n    ')
                    if bus == 'M_AXI' and sig == 'AWID':
                        attrs = ('(* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 M_AXI AWID" *)\n'
                                 '    (* X_INTERFACE_PARAMETER = "PROTOCOL AXI4, DATA_WIDTH 512, '
                                 'SUPPORTS_NARROW_BURST 0, MAX_BURST_LENGTH 64" *)\n    ')
                break
        pls.append('    %s%s wire %s%s' % (attrs, d, (w + ' ') if w else '', n))
    L.append(',\n'.join(pls))
    L.append(');\n')
    L.append('rocelet_top #(')
    L.append(',\n'.join('    .%s(%s)' % (n, n) for n, _ in params))
    L.append(') u_top (')
    L.append(',\n'.join('    .%s(%s)' % (n, n) for _, _, n in ports))
    L.append(');\n\nendmodule\n')
    return '\n'.join(L)


def main():
    path = os.path.join(ROOT, 'rtl', 'rocelet_bd.v')
    text = generate()
    if '--check' in sys.argv:
        ok = os.path.exists(path) and open(path).read() == text
        print('rocelet_bd.v %s' % ('up to date' if ok else 'STALE'))
        return 0 if ok else 1
    open(path, 'w').write(text)
    print('wrote rtl/rocelet_bd.v')
    return 0


if __name__ == '__main__':
    sys.exit(main())
